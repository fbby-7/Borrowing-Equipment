-- Read access for signed-in users to reference/inventory data.
create policy roles_read on roles for select to authenticated using (true);
create policy departments_read on departments for select to authenticated using (true);
create policy categories_read on equipment_categories for select to authenticated using (true);
create policy equipment_read on equipment for select to authenticated using (true);
create policy units_read on equipment_units for select to authenticated using (true);

-- Users can read their own profile; administrators/officers can read all profiles.
create policy users_self_read on users for select to authenticated using (auth_user_id=auth.uid() or public.current_app_role() in ('Administrator','Equipment Officer'));
create policy users_self_update on users for update to authenticated using (auth_user_id=auth.uid() or public.current_app_role()='Administrator') with check (auth_user_id=auth.uid() or public.current_app_role()='Administrator');

-- Borrowers see their own transactions; admins/officers see all.
create policy borrowings_read on borrowings for select to authenticated using (
  borrower_id=(select user_id from users where auth_user_id=auth.uid()) or public.current_app_role() in ('Administrator','Equipment Officer')
);
create policy borrowing_items_read on borrowing_items for select to authenticated using (
  borrowing_id in (select borrowing_id from borrowings where borrower_id=(select user_id from users where auth_user_id=auth.uid()) or public.current_app_role() in ('Administrator','Equipment Officer'))
);
create policy returns_read on returns for select to authenticated using (
  borrowing_id in (select borrowing_id from borrowings where borrower_id=(select user_id from users where auth_user_id=auth.uid()) or public.current_app_role() in ('Administrator','Equipment Officer'))
);
create policy return_items_read on return_items for select to authenticated using (
  return_id in (select return_id from returns where borrowing_id in (select borrowing_id from borrowings where borrower_id=(select user_id from users where auth_user_id=auth.uid()) or public.current_app_role() in ('Administrator','Equipment Officer')))
);
create policy maintenance_read on maintenance_records for select to authenticated using (reported_by=(select user_id from users where auth_user_id=auth.uid()) or public.current_app_role() in ('Administrator','Equipment Officer'));

-- Admin/officer inventory changes.
create policy equipment_admin_write on equipment for all to authenticated using (public.current_app_role() in ('Administrator','Equipment Officer')) with check (public.current_app_role() in ('Administrator','Equipment Officer'));
create policy units_admin_write on equipment_units for all to authenticated using (public.current_app_role() in ('Administrator','Equipment Officer')) with check (public.current_app_role() in ('Administrator','Equipment Officer'));
create policy categories_admin_write on equipment_categories for all to authenticated using (public.current_app_role() in ('Administrator','Equipment Officer')) with check (public.current_app_role() in ('Administrator','Equipment Officer'));

-- Borrowing creation is done through the secure RPC above. Admin/officer can manage approvals.
create policy borrowings_staff_write on borrowings for update to authenticated using (public.current_app_role() in ('Administrator','Equipment Officer')) with check (public.current_app_role() in ('Administrator','Equipment Officer'));
create policy returns_staff_write on returns for insert to authenticated with check (public.current_app_role() in ('Administrator','Equipment Officer'));
create policy return_items_staff_write on return_items for insert to authenticated with check (public.current_app_role() in ('Administrator','Equipment Officer'));
create policy maintenance_staff_write on maintenance_records for all to authenticated using (public.current_app_role() in ('Administrator','Equipment Officer')) with check (public.current_app_role() in ('Administrator','Equipment Officer'));

-- Useful reporting views.
create or replace view public.v_equipment_inventory as
select eu.unit_id, eu.asset_tag, eu.serial_number, eu.condition_status, eu.availability_status,
       e.equipment_name, e.brand, e.model, ec.category_name
from equipment_units eu join equipment e on e.equipment_id=eu.equipment_id
join equipment_categories ec on ec.category_id=e.category_id;

create or replace view public.v_active_borrowings as
select b.borrowing_id, b.borrow_date, b.expected_return_date, b.status, b.purpose,
       u.first_name || ' ' || u.last_name as borrower_name,
       count(bi.borrowing_item_id) as item_count
from borrowings b join users u on u.user_id=b.borrower_id
left join borrowing_items bi on bi.borrowing_id=b.borrowing_id and bi.item_status='Borrowed'
where b.status in ('Pending','Approved','Active','Partially Returned','Overdue')
group by b.borrowing_id,u.first_name,u.last_name;

