create index idx_borrowings_borrower on borrowings(borrower_id);
create index idx_borrowings_status on borrowings(status);
create index idx_borrowings_due on borrowings(expected_return_date);
create index idx_borrowing_items_unit on borrowing_items(unit_id);
create index idx_returns_borrowing on returns(borrowing_id);
create index idx_maintenance_unit on maintenance_records(unit_id);

