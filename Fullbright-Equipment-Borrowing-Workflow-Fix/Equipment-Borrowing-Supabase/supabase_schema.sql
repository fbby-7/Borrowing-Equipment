create table roles (
  role_id bigint generated by default as identity primary key,
  role_name text not null unique,
  description text
);

create table departments (
  department_id bigint generated by default as identity primary key,
  department_name text not null unique,
  location text
);

create table users (
  user_id bigint generated by default as identity primary key,
  auth_user_id uuid unique references auth.users(id) on delete cascade,
  department_id bigint references departments(department_id),
  role_id bigint not null references roles(role_id),
  employee_no text not null unique,
  first_name text not null,
  last_name text not null,
  email text not null unique,
  phone text,
  user_status text not null default 'Active' check (user_status in ('Active','Inactive','Suspended')),
  created_at timestamptz not null default now()
);

create table equipment_categories (
  category_id bigint generated by default as identity primary key,
  category_name text not null unique,
  description text
);

create table equipment (
  equipment_id bigint generated by default as identity primary key,
  category_id bigint not null references equipment_categories(category_id),
  equipment_name text not null,
  brand text,
  model text,
  description text,
  replacement_cost numeric(12,2) not null default 0 check (replacement_cost >= 0)
);

create table equipment_units (
  unit_id bigint generated by default as identity primary key,
  equipment_id bigint not null references equipment(equipment_id),
  asset_tag text not null unique,
  serial_number text unique,
  condition_status text not null default 'Good' check (condition_status in ('Excellent','Good','Fair','Damaged','For Repair')),
  availability_status text not null default 'Available' check (availability_status in ('Available','Borrowed','Reserved','Maintenance','Retired')),
  purchase_date date
);

create table borrowings (
  borrowing_id bigint generated by default as identity primary key,
  borrower_id bigint not null references users(user_id),
  approved_by bigint references users(user_id),
  borrow_date timestamptz not null default now(),
  expected_return_date date not null,
  purpose text not null,
  status text not null default 'Pending' check (status in ('Pending','Approved','Active','Partially Returned','Completed','Rejected','Cancelled','Overdue')),
  remarks text
);

create table borrowing_items (
  borrowing_item_id bigint generated by default as identity primary key,
  borrowing_id bigint not null references borrowings(borrowing_id) on delete cascade,
  unit_id bigint not null references equipment_units(unit_id),
  item_condition_out text not null check (item_condition_out in ('Excellent','Good','Fair','Damaged','For Repair')),
  item_status text not null default 'Borrowed' check (item_status in ('Borrowed','Returned','Lost','Damaged')),
  notes text,
  unique (borrowing_id, unit_id)
);

create table returns (
  return_id bigint generated by default as identity primary key,
  borrowing_id bigint not null references borrowings(borrowing_id),
  received_by bigint not null references users(user_id),
  return_date timestamptz not null default now(),
  remarks text
);

create table return_items (
  return_item_id bigint generated by default as identity primary key,
  return_id bigint not null references returns(return_id) on delete cascade,
  borrowing_item_id bigint not null references borrowing_items(borrowing_item_id),
  condition_in text not null check (condition_in in ('Excellent','Good','Fair','Damaged','For Repair')),
  damage_description text,
  missing_accessory text,
  unique (return_id, borrowing_item_id)
);

create table maintenance_records (
  maintenance_id bigint generated by default as identity primary key,
  unit_id bigint not null references equipment_units(unit_id),
  reported_by bigint not null references users(user_id),
  maintenance_type text not null check (maintenance_type in ('Preventive','Repair','Inspection','Cleaning')),
  start_date date not null,
  end_date date,
  issue_description text not null,
  action_taken text,
  maintenance_cost numeric(12,2) not null default 0 check (maintenance_cost >= 0),
  maintenance_status text not null default 'Open' check (maintenance_status in ('Open','In Progress','Completed','Cancelled')),
  check (end_date is null or end_date >= start_date)
);

create index idx_users_department on users(department_id);
