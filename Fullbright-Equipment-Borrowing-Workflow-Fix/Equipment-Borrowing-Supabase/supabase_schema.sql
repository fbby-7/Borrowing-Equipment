-- Create a user row automatically whenever a Supabase Auth account is created.
create or replace function public.handle_new_auth_user()
returns trigger language plpgsql security definer set search_path = public
as $$
declare student_role bigint;
begin
  select role_id into student_role from public.roles where role_name='Student' limit 1;
  insert into public.users(auth_user_id,role_id,employee_no,first_name,last_name,email)
  values(new.id,student_role, 'USR-' || upper(substr(replace(new.id::text,'-',''),1,8)),
         coalesce(new.raw_user_meta_data->>'first_name','User'),
         coalesce(new.raw_user_meta_data->>'last_name',''),
         coalesce(new.email,''))
  on conflict (auth_user_id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_auth_user();

-- Server-side helper for admin/officer checks.
create or replace function public.current_app_role()
returns text language sql stable security definer set search_path=public
as $$
  select r.role_name from public.users u join public.roles r on r.role_id=u.role_id where u.auth_user_id=auth.uid() limit 1;
$$;

-- Atomic borrowing function: inserts borrowing + items and marks units borrowed.
create or replace function public.create_borrowing(p_unit_ids bigint[], p_expected_return_date date, p_purpose text, p_remarks text default null)
returns bigint language plpgsql security definer set search_path=public
as $$
declare uid bigint; bid bigint; unit_id bigint;
begin
  select user_id into uid from public.users where auth_user_id=auth.uid() and user_status='Active';
  if uid is null then raise exception 'Active user profile not found'; end if;
  if coalesce(array_length(p_unit_ids,1),0)=0 then raise exception 'Select at least one equipment unit'; end if;
  if p_expected_return_date < current_date then raise exception 'Return date cannot be in the past'; end if;
  if exists(select 1 from equipment_units where unit_id=any(p_unit_ids) and availability_status <> 'Available') then raise exception 'One or more selected units are not available'; end if;
  insert into borrowings(borrower_id,expected_return_date,purpose,status,remarks) values(uid,p_expected_return_date,p_purpose,'Pending',p_remarks) returning borrowing_id into bid;
  foreach unit_id in array p_unit_ids loop
    insert into borrowing_items(borrowing_id,unit_id,item_condition_out,item_status) select bid,unit_id,condition_status,'Borrowed' from equipment_units where equipment_units.unit_id=unit_id;
    update equipment_units set availability_status='Borrowed' where equipment_units.unit_id=unit_id;
  end loop;
  return bid;
end;
$$;

